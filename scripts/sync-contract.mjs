#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const DEFAULT_SOURCE = "https://tubealfred.com/.well-known/tubealfred-youtube-operations.v1.json";
const CONTRACT_PATH = resolve("contracts/tubealfred-youtube-operations.v1.json");
const GENERATED_PATH = resolve("src/generated/operations.ts");
const PLUGIN_PATH = resolve("openclaw.plugin.json");
const args = process.argv.slice(2);
const check = args.includes("--check");
const sourceIndex = args.indexOf("--source");
const source = sourceIndex >= 0 ? args[sourceIndex + 1] : DEFAULT_SOURCE;

if (!source) throw new Error("--source requires a file path or URL");
const sourceText = source.startsWith("http://") || source.startsWith("https://")
  ? await fetch(source).then(async (response) => {
      if (!response.ok) throw new Error(`contract fetch failed with HTTP ${response.status}`);
      return response.text();
    })
  : await readFile(resolve(source), "utf8");
const manifest = JSON.parse(sourceText);

if (manifest.schema_version !== 1 || manifest.manifest_version !== "1.0.0") {
  throw new Error("unsupported TubeAlfred operation manifest version");
}
if (!Array.isArray(manifest.operations) || manifest.operation_count !== manifest.operations.length) {
  throw new Error("invalid TubeAlfred operation manifest");
}

const operations = manifest.operations.map((operation) => {
  const properties = {};
  const required = [];
  for (const parameter of operation.parameters) {
    properties[parameter.name] = {
      ...parameter.schema,
      ...(parameter.description && !parameter.schema.description
        ? { description: parameter.description }
        : {}),
    };
    if (parameter.required) required.push(parameter.name);
  }
  return {
    id: operation.id,
    name: operation.clients.agent_tool.name,
    description: operation.description,
    method: operation.method,
    path: operation.path,
    parameters: { type: "object", properties, required, additionalProperties: false },
    request_parameters: operation.parameters.map((parameter) => ({
      name: parameter.name,
      in: parameter.in,
      required: parameter.required,
      schema: parameter.schema,
    })),
  };
});
const contractText = `${JSON.stringify(manifest, null, 2)}\n`;
const generatedText = `// This file is generated by scripts/sync-contract.mjs. Do not edit.\n\nexport const MANIFEST_VERSION = ${JSON.stringify(manifest.manifest_version)};\n\nexport const OPERATIONS = ${JSON.stringify(operations, null, 2)} as const;\n\n`;
const plugin = JSON.parse(await readFile(PLUGIN_PATH, "utf8"));
plugin.contracts.tools = ["tubealfred_billing_usage", ...operations.map((operation) => operation.name)];
const pluginText = `${JSON.stringify(plugin, null, 2)}\n`;
const outputs = [
  [CONTRACT_PATH, contractText],
  [GENERATED_PATH, generatedText],
  [PLUGIN_PATH, pluginText],
];

if (check) {
  const stale = [];
  for (const [path, expected] of outputs) {
    const actual = await readFile(path, "utf8").catch(() => "");
    if (actual !== expected) stale.push(path);
  }
  if (stale.length) throw new Error(`generated contract files are stale: ${stale.join(", ")}`);
  process.stdout.write(`OpenClaw contract ${manifest.manifest_version} is current.\n`);
} else {
  for (const [path, value] of outputs) await writeFile(path, value, "utf8");
  process.stdout.write(`Generated ${operations.length} OpenClaw tools.\n`);
}
